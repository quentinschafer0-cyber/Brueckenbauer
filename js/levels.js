  // Seeded PRNG (mulberry32) + integer hash – generate() must be deterministic (no Math.random).
  function mulberry32(a) {
    return function () {
      a = (a + 0x6D2B79F5) | 0;
      var t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }
  function hashInts(list) {
    var h = 2166136261 >>> 0;
    for (var i = 0; i < list.length; i++) {
      h ^= list[i] | 0;
      h = Math.imul(h, 16777619) >>> 0;
      h ^= h >>> 13;
    }
    // murmur3 finaliser for good bit dispersion
    h ^= h >>> 16; h = Math.imul(h, 0x85ebca6b) >>> 0;
    h ^= h >>> 13; h = Math.imul(h, 0xc2b2ae35) >>> 0;
    h ^= h >>> 16;
    return h >>> 0;
  }

  // -----------------------------------------------------------------------------------------------
  // Local terrain geometry (same semantics as BB.Terrain, but independent of physics.js).
  // ground = surface polyline, x non-decreasing; solid = polyline closed downward.
  // -----------------------------------------------------------------------------------------------
  function surfaceY(ground, x) {
    var n = ground.length;
    if (x < ground[0][0]) return ground[0][1];
    if (x > ground[n - 1][0]) return ground[n - 1][1];
    var best = -Infinity;
    for (var i = 0; i < n - 1; i++) {
      var a = ground[i], b = ground[i + 1];
      if (x < a[0] || x > b[0]) continue;
      var y = b[0] === a[0] ? Math.max(a[1], b[1]) : a[1] + (b[1] - a[1]) * (x - a[0]) / (b[0] - a[0]);
      if (y > best) best = y;
    }
    return best === -Infinity ? ground[n - 1][1] : best;
  }
  function segDist(px, py, ax, ay, bx, by) {
    var dx = bx - ax, dy = by - ay, l2 = dx * dx + dy * dy;
    var t = l2 > 0 ? clamp(((px - ax) * dx + (py - ay) * dy) / l2, 0, 1) : 0;
    var qx = ax + t * dx - px, qy = ay + t * dy - py;
    return Math.sqrt(qx * qx + qy * qy);
  }
  function groundDistance(ground, x, y) {
    if (ground.length === 1) return Math.hypot(x - ground[0][0], y - ground[0][1]);
    var best = Infinity;
    for (var i = 0; i < ground.length - 1; i++) {
      var d = segDist(x, y, ground[i][0], ground[i][1], ground[i + 1][0], ground[i + 1][1]);
      if (d < best) best = d;
    }
    return best;
  }
  // Strictly inside the solid terrain (points on the surface/wall are NOT inside). For an x-monotone
  // polyline closed downward, a point off the boundary is inside iff it lies below the (highest)
  // surface at its x.
  function insideGround(ground, x, y) {
    return y < surfaceY(ground, x) - EPS && groundDistance(ground, x, y) > EPS;
  }
  // Ground flat (within tol) over [x0, x1], including vertices inside the range.
  function isFlat(ground, x0, x1, tol) {
    var y0 = surfaceY(ground, x0);
    if (Math.abs(surfaceY(ground, x1) - y0) > tol) return false;
    for (var i = 0; i < ground.length; i++) {
      var p = ground[i];
      if (p[0] >= x0 && p[0] <= x1 && Math.abs(p[1] - y0) > tol) return false;
    }
    return true;
  }
  // No steps / steep slopes over [x0, x1] (vehicles must be able to keep driving there).
  function isDrivableRun(ground, x0, x1) {
    for (var i = 0; i < ground.length - 1; i++) {
      var a = ground[i], b = ground[i + 1];
      if (b[0] < x0 || a[0] > x1) continue;
      var dx = b[0] - a[0], dy = b[1] - a[1];
      if (dx === 0) { if (Math.abs(dy) > V.maxStep) return false; }
      else if (Math.abs(dy / dx) > V.maxSlope) return false;
    }
    return true;
  }

  // -----------------------------------------------------------------------------------------------
  // stars / lookup / clone
  // -----------------------------------------------------------------------------------------------
  // cost ≤ 75 % of budget → 3★, ≤ 90 % → 2★, ≤ 100 % → 1★, else 0. budget null → 3.
  function stars(cost, budget) {
    if (budget === null || budget === undefined) return 3;
    var b = Number(budget), c = Number(cost);
    if (!isFinite(b) || b <= 0) return 3;          // no usable budget = unlimited
    if (!isFinite(c)) return 0;
    var t = (BB.Levels && BB.Levels.STAR_THRESHOLDS) || STAR_THRESHOLDS;
    var eps = b * 1e-9;                             // guards against 0.9·budget rounding below an exact cost
    if (c <= b * t[0] + eps) return 3;
    if (c <= b * t[1] + eps) return 2;
    if (c <= b + eps) return 1;
    return 0;
  }

  function index(id) {
    for (var i = 0; i < BB.LEVELS.length; i++) {
      if (BB.LEVELS[i] && BB.LEVELS[i].id === id) return i;
    }
    return -1;
  }
  // Returns the shared built-in level object (clone() it before mutating).
  function get(id) {
    var i = index(id);
    return i >= 0 ? BB.LEVELS[i] : null;
  }

  // Deep copy of plain data (objects, arrays, primitives).
  function clone(v) {
    if (Array.isArray(v)) return v.map(clone);
    if (v && typeof v === 'object') {
      var o = {};
      for (var k in v) if (Object.prototype.hasOwnProperty.call(v, k)) o[k] = clone(v[k]);
      return o;
    }
    return v;
  }

